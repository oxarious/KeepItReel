import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
const root = path.resolve('.output/chrome-mv3');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'manifest.json'), 'utf8'));
const pkg = JSON.parse(fs.readFileSync('package.json', 'utf8'));
assert.equal(manifest.manifest_version, 3);
assert.equal(manifest.version, pkg.version);
assert.equal(manifest.name, 'KeepItReel');
assert.equal(manifest.action.default_title, 'KeepItReel');
assert.deepEqual(manifest.permissions.toSorted(), ['activeTab', 'scripting', 'storage']);
assert.deepEqual(manifest.host_permissions || [], []);
assert.deepEqual(manifest.optional_host_permissions, ['http://*/*', 'https://*/*']);
assert.match(manifest.content_security_policy.extension_pages, /connect-src 'none'/);
assert.match(manifest.content_security_policy.extension_pages, /script-src 'self'/);
assert.equal(manifest.externally_connectable, undefined);
assert.equal(manifest.web_accessible_resources, undefined, 'No public extension resources are needed for injected typography');
const expectedMatches = ['*://www.youtube.com/*', '*://www.tiktok.com/*', ...['ca', 'co.uk', 'com.au', 'com', 'de', 'fr', 'se'].map(tld => `*://www.google.${tld}/search*`)];
assert.deepEqual(manifest.content_scripts.flatMap(s => s.matches).toSorted(), expectedMatches.toSorted());
for (const file of ['background.js', 'protection.js', 'extract.js', 'popup.html', 'options.html', 'demo.html', 'icon/128.png']) assert(fs.existsSync(path.join(root, file)), `Missing ${file}`);
const files = fs.readdirSync(root, { recursive: true }).filter(f => fs.statSync(path.join(root, f)).isFile());
assert(fs.existsSync(path.join(root, 'licenses/Atkinson-OFL.txt')), 'Missing bundled font licence');
const fonts = files.filter(f => f.endsWith('.woff2'));
assert.equal(fonts.length, 1, 'Package only the selected font family');
assert.equal(fs.readFileSync(path.join(root, fonts[0])).subarray(0, 4).toString(), 'wOF2');
const code = files.filter(f => /\.(js|html)$/.test(f)).map(f => fs.readFileSync(path.join(root, f), 'utf8')).join('\n');
assert(!code.includes('Clearfeed') && !code.includes('CLEARFEED'), 'Old display branding remains');
for (const retired of ['invitation-card__message', 'repeated-invitation', 'supabase.co', 'api.pangram.com', 'api.stripe.com', 'signInWithOtp']) assert(!code.includes(retired), `Disallowed release content: ${retired}`);
assert(code.includes('*://linkedin.com/*') && code.includes('*://*.linkedin.com/*'), 'Missing excluded-domain registration');
assert(!files.some(f => /(^|[\\/])(\.env|node_modules|supabase|tests)([.\\/]|$)/.test(f)), 'Source or secrets leaked into extension');
for (const file of files.filter(f => /\.html$/.test(f))) assert(!/<script[^>]+src=["']https?:/i.test(fs.readFileSync(path.join(root, file), 'utf8')), 'Remote script');
console.log(`PASS: public early-development release ${manifest.version}; ${files.length} packaged files; local-only CSP; no retired integration or cloud client.`);
